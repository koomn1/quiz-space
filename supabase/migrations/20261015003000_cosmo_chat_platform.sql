  ON public.cosmo_conversations (user_id, archived_at, updated_at DESC);

CREATE OR REPLACE FUNCTION public.touch_cosmo_conversation_on_message()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  UPDATE public.cosmo_conversations
  SET last_message_at = COALESCE(NEW.created_at, now()),
      updated_at = COALESCE(NEW.created_at, now()),
      revision = revision + 1
  WHERE id = NEW.conversation_id
    AND user_id = NEW.user_id;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.touch_cosmo_conversation_on_message() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS cosmo_messages_touch_conversation ON public.cosmo_messages;
CREATE TRIGGER cosmo_messages_touch_conversation
  AFTER INSERT ON public.cosmo_messages
  FOR EACH ROW EXECUTE FUNCTION public.touch_cosmo_conversation_on_message();

CREATE TABLE IF NOT EXISTS public.cosmo_file_assets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id text NOT NULL REFERENCES public.users(uid) ON DELETE CASCADE,
  conversation_id text REFERENCES public.cosmo_conversations(id) ON DELETE SET NULL,
  original_name text NOT NULL CHECK (char_length(original_name) BETWEEN 1 AND 255),
  detected_mime_type text NOT NULL CHECK (char_length(detected_mime_type) BETWEEN 3 AND 160),
  declared_mime_type text,
  size_bytes bigint NOT NULL CHECK (size_bytes > 0 AND size_bytes <= 52428800),
  sha256 text CHECK (sha256 IS NULL OR sha256 ~ '^[a-f0-9]{64}$'),
  storage_bucket text NOT NULL DEFAULT 'quiz-extraction-uploads',
  storage_path text NOT NULL UNIQUE,
  status text NOT NULL DEFAULT 'uploaded'
    CHECK (status IN ('uploaded', 'scanning', 'extracting', 'ready', 'failed', 'deleted', 'expired')),
  retention_expires_at timestamptz,
  error_code text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);
