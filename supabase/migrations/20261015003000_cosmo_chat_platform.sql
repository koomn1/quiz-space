CREATE OR REPLACE FUNCTION public.search_cosmo_content(p_query text, p_limit integer DEFAULT 30)
RETURNS TABLE (
  result_type text,
  result_id text,
  conversation_id text,
  title text,
  snippet text,
  created_at timestamptz
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
  WITH q AS (SELECT websearch_to_tsquery('simple', NULLIF(trim(p_query), '')) AS query),
  message_hits AS (
    SELECT 'message'::text, m.id, m.conversation_id, c.title,
      ts_headline('simple', m.text, q.query, 'MaxWords=35,MinWords=8') AS snippet,
      m.created_at
    FROM public.cosmo_messages m
    JOIN public.cosmo_conversations c ON c.id = m.conversation_id
    CROSS JOIN q
    WHERE m.user_id = (select auth.uid())::text
      AND c.user_id = (select auth.uid())::text
      AND m.status <> 'deleted'
      AND q.query IS NOT NULL
      AND to_tsvector('simple', m.text) @@ q.query
  )
  SELECT * FROM message_hits ORDER BY created_at DESC LIMIT LEAST(GREATEST(COALESCE(p_limit, 30), 1), 100);
$$;
REVOKE ALL ON FUNCTION public.search_cosmo_content(text, integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.search_cosmo_content(text, integer) TO authenticated;
